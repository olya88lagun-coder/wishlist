// Иконка карточки идеи по ключевым словам названия и запроса. Порядок важен: «кофемашина» — кухня, а не напиток
const RULES: ReadonlyArray<readonly [IdeaIcon, RegExp]> = [
  ["kitchen", /кофемашин|кофевар|капучинатор|мультивар|аэрогрил|духовк|мультипеч|мангал|гриль|кулинар|посуд|сковород|блендер/],
  ["ticket", /билет|концерт|спектакл|театр|выставк|кино|квиз|матч/],
  ["experience", /мастер-класс|курс|дегустац|абонемент|картинг|(?:^|[^а-яё])тир|скалодром|впечатлен|сертификат|квест|(?:^|[^а-яё])спа(?:$|[^а-яё])/],
  ["photo", /фотокниг|фото|постер|картин|альбом/],
  ["notebook", /ежедневник|блокнот|планер|календар/],
  ["book", /книг|комикс|манга|журнал|раскраск/],
  ["tech", /наушник|колонк|геймпад|(?:^|[^а-яё])мыш|камер|регистратор|часы|браслет|зарядк|пауэрбанк|приставк|планшет/],
  ["sport", /спорт|йог|фитнес|(?:^|[^а-яё])бег|кроссовк|велосипед|самокат|мяч|тренаж|танц|бассейн|лыж|ролик|санк|ватрушк|коньк/],
  ["tools", /отвёртк|отвертк|шуруповёрт|инструмент|(?:^|[^а-яё])бит|авто|компрессор|пылесос|дрель/],
  ["game", /набор для опытов|творчеств|(?:^|[^а-яё])игр|головолом|конструктор|пазл|лего/],
  ["drink", /кофе|чай|кружк|глинтвейн|шоколад|конфет|печень|сладост|чашк|бокал|(?:^|[^а-яё])мёд|(?:^|[^а-яё])мед/],
  ["beauty", /косметик|уход|крем|духи|парфюм|массаж|маникюр|ванн/],
  ["home", /плед|постельн|свеч|диффузор|ламп|гирлянд|тапоч|растени|кашпо|кресл|подушк|халат|ёлочн|елочн|увлажнит|очистител/],
  ["wallet", /кошел|картхолдер|сумк|ремень|рюкзак|брелок|украшен|серьг|кольц/],
];

export type IdeaIcon = "kitchen" | "ticket" | "experience" | "notebook" | "book" | "tech" | "sport" | "tools" | "game" | "drink" | "beauty" | "home" | "wallet" | "photo" | "gift";

export function ideaIcon(idea: { name: string; query?: string }): IdeaIcon {
  const text = `${idea.name} ${idea.query ?? ""}`.toLowerCase();
  return RULES.find(([, pattern]) => pattern.test(text))?.[0] ?? "gift";
}
