type Slug = keyof typeof PAGES;

export const dynamic = "force-dynamic";

export async function generateMetadata({ params }: { params: Promise<{ slug: string }> }): Promise<Metadata> {
  const { slug } = await params;
  const page = PAGES[slug as Slug];
  if (!page) return {};
  return {
    title: page.title,
    description: page.description,
    alternates: { canonical: `/gifts/${slug}` },
  };
}

export default async function GiftRecipientPage({ params }: { params: Promise<{ slug: string }> }) {
  const { slug } = await params;
  const page = PAGES[slug as Slug];
  if (!page) notFound();

  const { user } = await readViewer();
  const wishlists = user ? await listWishlistsForOwner(getDb(), user.id) : [];

  return (
    <main className="page page--wide gifts-page">
      <p className="eyebrow">my wish list · идеи подарков</p>
      <h1 className="display">{page.heading}</h1>
      <p className="gifts-page__lead">{page.intro}</p>

      <section className="gifts-page__seo">
        <h2>Как подойти к выбору</h2>
        <ul>
          {page.tips.map((tip) => <li key={tip}>{tip}</li>)}
        </ul>
      </section>

      <GiftFinder wishlists={wishlists} initialPerson={page.person} />

      <section className="gifts-page__seo">
        <p className="eyebrow">Ещё идеи</p>
        <h2>Подберите подарок по конкретным условиям</h2>
        <p className="muted">Можно изменить повод, интересы и бюджет в форме выше или перейти к общему AI-помощнику.</p>
        <a className="button button--ghost button--small" href="/gifts">Открыть подбор подарка</a>
      </section>
    </main>
  );
}
